def old_profile(home):
    data = read_toml(home / ".config/chezmoi/chezmoi.toml").get("data", {})
    pins = dict(data.get("miseTools", {}))
    current_mise = read_toml(home / ".config/mise/config.toml")
    current = current_mise.get("tools", {})
    pins.update(current)
    saved = read_toml(home / ".config/dotfiles/profile.toml")
    pins.update(
        saved.get("miseTools", saved.get("tool_pins", saved.get("pins", saved.get("tools", {}))))
    )
    profile = {
        "content_repo": saved.get("content_repo", DEFAULT_REPO),
        "domain": saved.get("domain", data.get("domain", "core")),
        "git_name": saved.get("git_name", saved.get("gitName", data.get("gitName", ""))),
        "git_email": saved.get("git_email", saved.get("gitEmail", data.get("gitEmail", ""))),
        "pins": pins,
        "groups": saved.get("groups", {}),
    }
    # Carry-over is not evidence of a choice in this wizard.
    profile["domain_chosen"] = False
    if "settings" in current_mise:
        profile["mise_settings"] = current_mise["settings"]
    if data.get("secretsEnabled"):
        profile["secrets"] = {
            "EXAMPLE_API_TOKEN": {"enabled": True, "reference": data["secretReference"]}
        }
    if saved.get("secrets"):
        profile["secrets"] = saved["secrets"]
    sources = []
    if data:
        sources.append("old chezmoi data")
    if current:
        sources.append("current Mise tools")
    if saved:
        sources.append("saved installer profile")
    return profile, sources


def reconcile_config_template_state():
    """Acknowledge templates without letting them write the manager's config."""
    # source-path accounts for a native repository's .chezmoiroot.
    source = Path(run("chezmoi", "source-path").strip())
    templates = [
        source / f".chezmoi.{extension}.tmpl"
        for extension in ("json", "jsonc", "toml", "yaml", "yml")
        if (source / f".chezmoi.{extension}.tmpl").exists()
    ]
    if len(templates) > 1:
        raise ValueError(
            "Multiple chezmoi config templates exist; keep only one in the content repository."
        )
    # Match chezmoi's configState record. Leave file and script history intact.
    # https://github.com/twpayne/chezmoi/blob/v2.74.1/internal/cmd/config.go
    args = ["chezmoi", "state"]
    if templates:
        state = {
            "configTemplateContentsSHA256": hashlib.sha256(templates[0].read_bytes()).hexdigest()
        }
        run(
            *args,
            "set",
            "--bucket=configState",
            "--key=configState",
            "--value=" + json.dumps(state),
        )
    else:
        run(*args, "delete", "--bucket=configState", "--key=configState")


def exact_version(version):
    """Require a full numeric release or a complete Git commit identifier."""
    return isinstance(version, str) and bool(
        re.fullmatch(
            r"(?:[A-Za-z][A-Za-z0-9_-]*-)?v?\d+(?:\.\d+){2,}(?:[a-zA-Z][0-9A-Za-z._-]*|[-+][0-9A-Za-z][0-9A-Za-z.+-]*)?"
            r"|\d{4}-\d{2}-\d{2}|[0-9a-f]{40}",
            version,
        )
    )


def resolve_installed_pin(home, tool, request):
    result = subprocess.run(
        ["mise", "latest", "--installed", "--cd", str(home), f"{tool}@{request}"],
        text=True,
        capture_output=True,
    )
    version = result.stdout.strip()
    return version if result.returncode == 0 and exact_version(version) else None


def has_terminal():
    if os.environ.get("FLEET_REMOTE_RUN") == "1":
        return False
    try:
        descriptor = os.open("/dev/tty", os.O_RDWR)
    except OSError:
        return False
    os.close(descriptor)
    return True


def profile_gaps(profile):
    gaps = []
    if not profile.get("domain_chosen", False):
        gaps.append(
            f"Domain was never explicitly chosen (recorded: {profile.get('domain', 'core')}). Supply --domain."
        )
    for field, label, flag in [
        ("git_name", "Git name", "--git-name"),
        ("git_email", "Git email", "--git-email"),
    ]:
        if not profile.get(field, "").strip():
            gaps.append(f"{label} is empty. Supply {flag}.")
    for tool, request in profile.get("pins", {}).items():
        for item in request if isinstance(request, list) else [request]:
            version = item.get("version", "") if isinstance(item, dict) else item
            if not exact_version(version):
                gaps.append(
                    f"{tool} tool version is floating (recorded: {version}). Supply --tool {tool}=VERSION with a full version."
                )
    return gaps


def require_complete_profile(profile):
    gaps = profile_gaps(profile)
    if gaps:
        raise ValueError(
            "Non-interactive setup needs a complete profile:\n- "
            + "\n- ".join(gaps)
            + "\nProvide these flags, or run in a terminal without --defaults."
        )


def pin_argument(text):
    tool, separator, version = text.partition("=")
    if (
        not separator
        or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9:._@/-]*", tool)
        or not version.strip()
    ):
        raise argparse.ArgumentTypeError("--tool needs TOOL=VERSION, for example node=24.14.1")
    return tool, version.strip()


def domain_argument(text):
    from convert import DOMAIN_NAME

    if not DOMAIN_NAME.fullmatch(text):
        raise argparse.ArgumentTypeError(
            "--domain needs a domain name: lowercase letters, digits, and single hyphens"
        )
    return text


def group_argument(text):
    name, separator, choice = text.partition("=")
    if not separator or not name or choice not in ("on", "off"):
        raise argparse.ArgumentTypeError("--group needs NAME=on or NAME=off")
    return name, choice


def validate_profile(home, profile, defaults=False, configure=False, checkout=None):
    """Ask about gaps and return warnings for choices left incomplete."""
    warnings = []
    if defaults:
        require_complete_profile(profile)
    # Old core defaults have no proof of an explicit choice. Ask once and record it.
    profile.setdefault("domain_chosen", False)
    if not defaults and (configure or not profile["domain_chosen"]):
        domain = ask(
            "Domain",
            profile.get("domain", "core"),
            [*content_domains(content_manifest(checkout) if checkout else {}), "skip"],
            defaults,
            heading="Choose your domain",
            detail=domain_details(
                checkout,
                profile.get("domain", "core"),
                "current" if profile["domain_chosen"] else "recommended",
            ),
        )
        if domain != "skip":
            profile["domain"] = domain
            if not defaults:
                profile["domain_chosen"] = True
    if not profile["domain_chosen"]:
        warnings.append("No domain choice confirmed. The recorded domain remains in use.")
    if not defaults and (
        configure
        or not profile.get("git_name", "").strip()
        or not profile.get("git_email", "").strip()
    ):
        for field, label, noun in [
            ("git_name", "Git author name", "name"),
            ("git_email", "Git author email", "email address"),
        ]:
            recorded = profile.get(field, "")
            keep = f"keep {recorded}" if recorded else "leave it empty"
            answer = ask(
                label,
                recorded,
                defaults=defaults,
                heading="Git commit identity",
                detail=(
                    f"Git records this {noun} on commits. Type your {noun}.\n"
                    "  skip  Leave the saved value unchanged.\n"
                    f"Press Enter alone to {keep}."
                ),
            )
            if answer != "skip":
                profile[field] = answer
    if not profile.get("git_name", "").strip() or not profile.get("git_email", "").strip():
        warnings.append(
            "No complete git identity recorded. Git commits will fail until one is set."
        )
    pins = profile.setdefault("pins", {})
    unpinned = set(profile.get("unpinned_tools", []))
    for tool, request in list(pins.items()):
        entries = request if isinstance(request, list) else [request]
        resolved = []
        for item in entries:
            version = item.get("version", "") if isinstance(item, dict) else item
            if not exact_version(version):
                recorded = str(version)
                installed = resolve_installed_pin(home, tool, recorded)
                action = (
                    f"uses installed {installed}" if installed else "leaves this tool unselected"
                )
                label = f"{tool} version"
                detail = f"Recorded value: {recorded}.\n"
                if not installed:
                    detail += "For this tool, no matching version is installed.\n"
                detail += (
                    "Type a full version, such as 24.14.1.\n"
                    "  skip  Leave this tool unselected.\n"
                    f"Press Enter alone: Fleet {action}."
                )
                while True:
                    answer = ask(
                        label,
                        recorded,
                        defaults=defaults,
                        heading="Choose an exact tool version",
                        detail=detail,
                    )
                    if answer == "skip":
                        version = None
                        break
                    if answer == recorded:
                        version = installed
                        break
                    if exact_version(answer):
                        version = answer
                        break
                    print("Use a full version, such as 24.14.1, or type skip.")
                if version is None:
                    warnings.append(
                        f"{tool}: skipped floating version {recorded}. No version was recorded for this entry."
                    )
                    continue
                print(f"Recorded exact version: {tool} = {version}")
            resolved.append(dict(item, version=version) if isinstance(item, dict) else version)
        if resolved:
            unpinned.discard(tool)
            pins[tool] = resolved if isinstance(request, list) else resolved[0]
        else:
            del pins[tool]
            unpinned.add(tool)
    if unpinned or "unpinned_tools" in profile:
        profile["unpinned_tools"] = sorted(unpinned)
    for tool in sorted(unpinned):
        warnings.append(f"{tool} has no selected version. Content defaults will not select it.")
    return warnings


def ask_machine_name(home):
    """Ask for this WSL distro's fleet name once, then save the accepted answer."""
    import registry

    detail = "\n".join(
        [
            "Name this WSL distro in the fleet. Other machines list it by this name.",
            "Fleet proposed host, distro, version, and scope from this distro. "
            "Type another name to change it.",
            "Use letters, digits, dots, hyphens, and underscores. "
            "Fleet never renames a machine later.",
            "Press Enter to accept the proposed name.",
        ]
    )
    proposed = registry.proposed_name(home=home)
    while True:
        answer = ask("Machine name", proposed, detail=detail, heading="Machine name")
        if not registry.NAME.fullmatch(answer):
            print("Use letters, digits, dots, hyphens, and underscores.")
        elif answer in registry.taken_names(home):
            print(f"{answer} belongs to another machine. Choose another name.")
        else:
            registry.save_name(home, answer)
            return answer


