def prompt_style(name, text, terminal=None):
    return style.paint(name, text, terminal, bold=name == "CYAN")


def ask(label, default, choices=None, defaults=False, *, detail="", heading=None, formatted=False):
    if defaults:
        return default
    try:
        with open("/dev/tty", "r") as reader, open("/dev/tty", "w") as terminal:
            while True:
                terminal.write(
                    "\n" + prompt_style("CYAN", style.section(heading or label), terminal) + "\n"
                )
                if detail:
                    width = max(30, min(os.get_terminal_size(terminal.fileno()).columns or 80, 100))
                    for line in detail.splitlines():
                        indent = " " * 12 if line.startswith("  ") else ""
                        value = (
                            line
                            if formatted
                            else textwrap.fill(
                                line,
                                width,
                                subsequent_indent=indent,
                                break_long_words=False,
                                break_on_hyphens=False,
                            )
                        )
                        palette = (
                            {"+": "GREEN", "−": "RED", "~": "YELLOW"}.get(change_marker(line))
                            if formatted
                            else None
                        )
                        terminal.write(prompt_style(palette or "BLUE", value, terminal) + "\n")
                    terminal.write("\n")
                terminal.write(prompt_style("GREEN", f"{label} [{default}]: ", terminal))
                terminal.flush()
                answer = reader.readline()
                if not answer:
                    raise ValueError("Terminal input ended; no answer was accepted.")
                answer = answer.strip() or default
                if choices is None or answer in choices:
                    terminal.write("\n")
                    terminal.flush()
                    return answer
                terminal.write(
                    "\n"
                    + prompt_style(
                        "YELLOW",
                        "Choose " + ", ".join(choices) + ". Press Enter to submit.",
                        terminal,
                    )
                    + "\n"
                )
    except OSError as error:
        raise ValueError(
            "Setup needs a terminal. Supply explicit profile flags for a scripted run."
        ) from error


def options(rows, default, mark="recommended", intro=""):
    """Return prompt text: one line per choice, then what Enter alone does.

    Each row is (word, effect). Mark names the default as recommended or current; None marks nothing.
    """
    width = max(len(word) for word, _ in rows)
    lines = [intro] if intro else []
    for word, effect in rows:
        note = f" ({mark.capitalize()}.)" if word == default and mark else ""
        lines.append(f"  {word:<{width}}  {effect}{note}")
    lines.append(f"Press Enter alone to choose {default}.")
    return "\n".join(lines)


def domain_details(checkout, default="core", mark="current"):
    """Describe actual domain alias additions without executing their shell code.

    List one line per domain word, mark the default, and state what Enter alone does.
    """
    entries = tracked(checkout) if checkout is not None else {}
    lines = [
        "Your domain chooses optional additions from the content repository.",
        "Git identity and tool versions are chosen separately.",
        "",
    ]
    if checkout is not None:
        base = []
        for label, paths in [
            ("shell startup", [".zshrc", ".bashrc"]),
            ("shared command shortcuts", [".config/dotfiles/aliases/core.zsh"]),
            ("Git defaults", [".gitconfig"]),
            ("prompt appearance", [".config/starship.toml"]),
        ]:
            if any(path in entries for path in paths):
                base.append(label)
        if base:
            lines += ["Base files in this checkout: " + ", ".join(base) + ".", ""]
    manifest = content_manifest(checkout) if checkout else {}
    descriptions = manifest.get("domains", {})

    def note(name):
        return f" ({mark.capitalize()}.)" if name == default else ""

    lines.append("  core      Base configuration only. No domain additions." + note("core"))
    if descriptions.get("core"):
        lines.append("            " + descriptions["core"])
    empty = 0
    additions = content_domains(manifest)[1:]
    for domain in additions:
        name = f".config/dotfiles/aliases/{domain}.zsh"
        if entries.get(name) not in ("100644", "100755"):
            summary = (
                "Additions are not described here. Check the content repository documentation."
            )
        else:
            content = run("git", "-C", str(checkout), "show", ":" + name)
            active = [
                line
                for line in content.splitlines()
                if line.strip() and not line.lstrip().startswith("#")
            ]
            if not active:
                summary = "Adds nothing yet. Add your own settings here."
                empty += 1
            else:
                names = re.findall(r"^\s*alias\s+([A-Za-z_][A-Za-z_0-9-]*)=", content, re.M)
                names += re.findall(r"^\s*([A-Za-z_][A-Za-z_0-9-]*)\s*\(\)\s*\{", content, re.M)
                summary = (
                    "Command names: " + ", ".join(dict.fromkeys(names)) + "."
                    if names
                    else "Contains custom shell settings."
                )
                summary += f" Review .config/dotfiles/aliases/{domain}.zsh for their behavior."
        lines.append(f"  {domain:<9} {summary}{note(domain)}")
        if descriptions.get(domain):
            lines.append("            " + descriptions[domain])
    if additions and empty == len(additions):
        lines += ["", "No declared domain adds commands yet. Start with core."]
    lines += [
        "",
        "Your content declares these domains. Add or remove domains in its fleet.toml.",
        "Choosing a domain does not install software or create accounts.",
        "Your choice is saved in ~/.fleet/profile.toml.",
        "",
        f"  skip      Keep {default} for now without confirming it as your choice.",
        f"Type a domain name, or press Enter alone to choose {default}.",
    ]
    return "\n".join(lines)


