def select_profile(home, args, workspace):
    import enrollment as wizard

    path = home / ".fleet/profile.toml"
    exists = path.exists()
    profile, sources = (
        (read_toml(path), ["existing Fleet profile"]) if exists else old_profile(home)
    )
    profile.setdefault("domain_chosen", False)
    if args.domain is not None:
        profile.update(domain=args.domain, domain_chosen=True)
    for field in ("git_name", "git_email"):
        if getattr(args, field) is not None:
            profile[field] = getattr(args, field).strip()
    for tool, version in args.pin:
        previous = profile.setdefault("pins", {}).get(tool)
        profile["pins"][tool] = (
            dict(previous, version=version) if isinstance(previous, dict) else version
        )
    unattended = args.defaults or not has_terminal()
    args.wizard = not unattended and (
        not exists or bool(profile_gaps(profile)) or args.configure or args.adopt
    )
    profile.setdefault("pins", {})
    profile.setdefault("secrets", {})
    if args.wizard:
        if (
            os.environ.get("WSL_DISTRO_NAME")
            and not args.machine_name
            and not run_index.saved_name(home)
            and not exists
        ):
            ask_machine_name(home)
        args.scan_record = {}
        args.found, args.excluded = wizard.welcome(home, sources, profile, args.scan_record)
        profile, checkout, manifest, warnings = wizard.steps(
            home, args, workspace, profile, args.found, args.excluded
        )
        return profile, sources, checkout, manifest, warnings
    if getattr(args, "edit", None):
        args.edit(profile)
    require_complete_profile(profile)
    repo = args.repo or profile.get("content_repo", DEFAULT_REPO)
    if args.adopt:
        found, excluded = wizard.scan(home)
        for line in wizard.scan_view.exclusions(excluded):
            print(line)
        name = dotfiles_library.free_name(
            home, dotfiles_library.ADOPTED, has_terminal(), reuse="local"
        )
        checkout = wizard.adopt(home, workspace, found, excluded, name)
        repo = str(dotfiles_library.path(home, name))
        profile.update(adopted=True, adoption_excluded=sorted(excluded), source_door="adopt")
    else:
        name = args.dotfiles or dotfiles_library.name_for_source(
            home, repo, profile, has_terminal()
        )
        checkout = wizard.stage_repo(home, repo, workspace, name)
    profile["dotfiles"] = name
    # A switch reads the new repository's own format; the saved one belongs to the old one.
    kind, manifest = detect(
        checkout, args.format or (None if args.dotfiles else profile.get("format"))
    )
    profile.update(content_repo=repo, format=kind, adopted=bool(manifest.get("adopted", False)))
    warnings = validate_profile(home, profile, True, checkout=checkout)
    wizard.group_flags(profile, args.group, manifest)
    selections = profile.setdefault("groups", {})
    for group, spec in manifest.get("groups", {}).items():
        if group not in selections:
            choice = ask(
                group,
                "on",
                ["on", "off"],
                unattended,
                detail=options(
                    [("on", "Include this new group."), ("off", "Leave it out.")],
                    "on",
                    intro=spec["description"] + ".",
                ),
            )
            if unattended:
                print(f"Group {group}: using {choice} ({spec['description']}).")
            selections[group] = choice == "on"
    if args.agents is not None:
        wizard.agent_flags(profile, args.agents)
    profile.setdefault("agents", {name: False for name in wizard.agent_manifest()})
    return profile, sources, checkout, manifest, warnings


def installed_defaults(defaults, pins, home):
    installed = json.loads(run("mise", "ls", "--installed", "--json", "--cd", str(home)))
    effective = dict(pins)
    available = {}
    for tool, request in defaults.items():
        if tool in pins:
            continue
        if not installed.get(tool):
            available[tool] = request
            continue
        requests = request if isinstance(request, list) else [request]
        matches = []
        for item in requests:
            version = item.get("version", "") if isinstance(item, dict) else item
            if not isinstance(version, str) or not version:
                matches.append(False)
                continue
            resolved = resolve_installed_pin(home, tool, version)
            matches.append(
                dict(item, version=resolved) if isinstance(item, dict) and resolved else resolved
            )
        if all(matches):
            effective[tool] = matches if isinstance(request, list) else matches[0]
        else:
            available[tool] = request
    return effective, available


def mise_handover(home, generated):
    """Return the user's own entries in the Mise config Fleet wrote before, as TOML bytes.

    Entries equal to what Fleet wrote leave with Fleet. Entries the user added or changed, for
    example with mise use -g, stay. Return b"" when none remain, and None when no file exists.
    """
    path = home / USER_MISE
    if not path.is_file() or path.is_symlink():
        return None
    current = read_toml(path)
    written = home / ".fleet/chezmoi-source" / source_name(USER_MISE)
    previous = (
        read_toml(written)
        if written.is_file()
        else tomllib.loads(generated.get(MISE, b"").decode() or "")
    )
    residue = {}
    for table, values in current.items():
        before = previous.get(table)
        if isinstance(values, dict):
            before = before if isinstance(before, dict) else {}
            kept = {key: item for key, item in values.items() if before.get(key) != item}
            if kept:
                residue[table] = kept
        elif before != values:
            residue[table] = values
    return toml_tables(residue).encode() if residue else b""


def hand_over_mise(home, content, backup_path):
    """Leave the global Mise config to the user, with only the user's own entries."""
    path = home / USER_MISE
    if content:
        atomic(path, content, path.stat().st_mode & 0o777)
        print(
            "Mise: ~/.config/mise/config.toml keeps only your own entries, and they take"
            " precedence. Fleet's pins moved to ~/.config/mise/conf.d/fleet.toml."
        )
    else:
        retired = backup_path / "retired" / USER_MISE
        retired.parent.mkdir(parents=True, exist_ok=True)
        path.rename(retired)
        print("Mise: Fleet's pins moved to ~/.config/mise/conf.d/fleet.toml.")
    # chezmoi forgets the file, so a later mise use -g is never a conflict.
    run("chezmoi", "state", "delete", "--bucket=entryState", "--key=" + str(path))


def fingerprint(path):
    if path.is_symlink():
        return {"link": os.readlink(path)}
    if path.is_file():
        return {
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "mode": path.stat().st_mode & 0o777,
        }
    return None


def backup_location(home):
    root = home / ".fleet/backups"
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    destination = root / stamp
    suffix = 0
    while destination.exists():
        suffix += 1
        destination = root / f"{stamp}-{suffix}"
    return destination


def backup_inventory(home, paths):
    entries = []
    for name in sorted(set(paths)):
        path = home / relative(name)
        if not path.parent.resolve().is_relative_to(home.resolve()):
            raise ValueError(f"Managed parent leaves HOME: {name}")
        if not path.exists() and not path.is_symlink():
            entries.append({"path": name, "state": "absent"})
            continue
        item = {"path": name, "state": "saved", "fingerprint": fingerprint(path)}
        if path.is_symlink():
            item["link"] = os.readlink(path)
            resolved = path.resolve()
            if resolved.is_file() and not resolved.is_relative_to(home.resolve()):
                item["external"] = str(resolved)
        entries.append(item)
    return entries


def backup(home, paths, destination=None):
    entries = backup_inventory(home, paths)
    destination = destination or backup_location(home)
    destination.parent.mkdir(exist_ok=True, mode=0o700)
    destination.mkdir(mode=0o700)
    for item in entries:
        if item["state"] == "absent":
            continue
        path = home / item["path"]
        target = destination / "home" / item["path"]
        target.parent.mkdir(parents=True, exist_ok=True)
        if path.is_symlink():
            target.symlink_to(os.readlink(path))
        elif path.is_dir():
            shutil.copytree(path, target, symlinks=True, dirs_exist_ok=True)
        else:
            shutil.copy2(path, target)
        if "external" in item:
            external = destination / "external" / item["external"].lstrip("/")
            external.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(item["external"], external)
    atomic(destination / "MANIFEST.json", json.dumps(entries, indent=2) + "\n")
    return destination


def generated_files(home, profile, manifest, defaults):
    allowed_defaults = {
        tool: version
        for tool, version in defaults.get("tools", {}).items()
        if tool not in profile.get("unpinned_tools", [])
    }
    pins, available = installed_defaults(allowed_defaults, profile["pins"], home)
    mise = dict(defaults)
    mise["tools"] = pins
    if "mise_settings" in profile:
        mise["settings"] = profile["mise_settings"]
    mise.setdefault("settings", {})
    mise["settings"].setdefault("experimental", False)
    with tempfile.TemporaryDirectory() as folder:
        local = Path(folder) / "local.gitconfig"
        previous = home / ".config/git/local.gitconfig"
        local.write_bytes(
            previous.read_bytes()
            if previous.is_file()
            else b"# Machine settings generated by Fleet.\n"
        )
        for key, field in [("user.name", "git_name"), ("user.email", "git_email")]:
            subprocess.run(
                ["git", "config", "--file", str(local), "--unset-all", key], capture_output=True
            )
            if profile.get(field):
                run("git", "config", "--file", str(local), key, profile[field])
        identity = local.read_bytes()
    references = dict(manifest.get("secrets", {}))
    references.update(profile.get("secrets", {}))
    active = {key: item for key, item in references.items() if item.get("enabled")}
    if active:
        lines = ["# Generated by Fleet. Never commit secret values."]
        for key, item in sorted(active.items()):
            if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", key) or not item["reference"].startswith(
                "op://"
            ):
                raise ValueError(
                    "Secret entries need a shell variable name and an op:// reference."
                )
            secret = run("op", "read", "--no-newline", item["reference"])
            lines.append(f"export {key}={shlex.quote(secret)}")
        secrets = ("\n".join(lines) + "\n").encode()
    else:
        previous = home / ".secrets"
        secrets = previous.read_bytes() if previous.is_file() else PLACEHOLDER
    return (
        {
            ".config/git/local.gitconfig": identity,
            ".config/dotfiles/domain": (profile["domain"] + "\n").encode(),
            MISE: toml_tables(mise).encode(),
            ".secrets": secrets,
        },
        pins,
        available,
    )


def rendering_profile(profile, manifest, switching):
    """Return the profile to render with. Keep the saved domain; fall back to core only on a switch.

    A repository chosen by dotfiles use may lack the saved domain; it applies core instead.
    Within one repository, a removed domain still stops before any plan or write.
    """
    domain = profile.get("domain", "core")
    if domain in content_domains(manifest):
        profile.pop("domain_fallback", None)
        return profile
    if switching:
        profile["domain_fallback"] = profile.get("dotfiles", "")
    if switching or profile.get("domain_fallback") == profile.get("dotfiles"):
        print(
            f"Domain {domain} is not declared by this repository; applying core. "
            f"Your saved domain stays {domain}."
        )
        return dict(profile, domain="core")
    require_domain(manifest, domain, command_name(profile))
    return profile


