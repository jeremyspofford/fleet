def publish_checkout(home, checkout, profile, backup_path):
    canonical = dotfiles_library.active(home, profile)
    shown = "~/" + dotfiles_library.LIBRARY + "/" + canonical.name
    if canonical.exists():
        # Recheck local edits after review. Fetch exactly the reviewed commit, never a newer remote tip.
        from updates import managed_edits

        if managed_edits(canonical):
            raise ValueError("Content changed during review. Preserve edits and run setup again.")
        commit = run("git", "-C", str(checkout), "rev-parse", "HEAD").strip()
        if (
            profile.get("source_door") == "adopt"
            and not subprocess.run(
                ["git", "-C", str(checkout), "config", "--get", "remote.origin.url"],
                capture_output=True,
            ).stdout
        ):
            canonical.rename(backup_path / "previous-content")
            shutil.copytree(checkout, canonical, symlinks=True)
        else:
            run("git", "-C", str(canonical), "fetch", str(checkout), commit)
            merged = subprocess.run(
                ["git", "-C", str(canonical), "merge", "--ff-only", commit],
                text=True,
                capture_output=True,
            )
            if merged.returncode:
                # Only an unmanaged local file that this update also changes reaches here.
                raise ValueError(
                    f"The update changes a file that has uncommitted local edits in {shown}."
                    " Commit or move that file, then run the update again.\n"
                    + merged.stderr.strip()
                )
    else:
        canonical.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        shutil.copytree(checkout, canonical, symlinks=True)
    # A newly adopted repository intentionally has no remote or saved credentials.
    if profile.get("adopted"):
        print(
            (
                f"Adopted repository: {shown}. Create an empty remote, then run git "
                "remote add origin URL and git push -u origin main."
            )
        )
    return canonical


