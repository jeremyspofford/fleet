def kept_files_message(status):
    """Name each differing file and the command that takes Fleet's version."""
    paths = [line[3:] for line in status.splitlines() if len(line) > 3]
    shown = ", ".join("~/" + path for path in paths)
    commands = " ".join("~/" + shlex.quote(path) for path in paths)
    return (
        f"Managed files still differ after the apply: {shown}. "
        "A local edit was kept at the conflict prompt. "
        f"To take Fleet's version, run: chezmoi apply --force {commands}. "
        "This run's backup holds your edited copy."
    )


def apply_confirmed_plan(
    home, checkout, profile, plan, backup_path, account, before_apply, warnings
):
    import agent_deploy
    from run_account import RECORD

    publish_checkout(home, checkout, profile, backup_path)
    account.applied_checkouts.add("Content")
    account.save()
    from installation import publish

    publish(home, ROOT, backup_path)
    account.applied_checkouts.add("Manager")
    previous = json.loads((home / RECORD).read_text()) if (home / RECORD).is_file() else {}
    previous["manager_commit"] = account.checkouts[0]["new"]
    atomic(home / RECORD, json.dumps(previous) + "\n")
    account.applied_software.add("dotfleet")
    account.save()
    if any(item["name"] == tui_environment.NAME for item in account.software):
        tui_environment.install(home, ROOT, backup_path, account)
    if before_apply:
        before_apply(account)
    account.save()
    # Temporary downloads become local tools only after review and backup.
    for tool in ["chezmoi", "mise"]:
        supplied = os.environ.get("DOTFLEET_STAGED_" + tool.upper())
        if supplied:
            atomic(home / ".local/bin" / tool, Path(supplied).read_bytes(), 0o700)
            account.applied_software.add("Mise" if tool == "mise" else tool)
            account.save()
    stable_source = Path(plan["config"]["sourceDir"])
    if not plan["native"]:
        stable_source.parent.mkdir(parents=True, exist_ok=True)
        if stable_source.exists():
            stable_source.rename(backup_path / "previous-chezmoi-source")
        shutil.copytree(plan["source"], stable_source, symlinks=True)
    atomic(home / ".config/chezmoi/chezmoi.toml", toml(plan["config"]))
    reconcile_config_template_state()
    profile_path = home / ".fleet/profile.toml"
    if not profile_path.exists() or read_toml(profile_path) != profile:
        atomic(profile_path, toml(profile))
    account.profile_written = True
    account.save()
    if plan["native"]:
        for name, content in plan["generated"].items():
            atomic(home / name, content)
    for name in plan["stale"]:
        path = home / name
        if path.exists() or path.is_symlink():
            retired = backup_path / "retired" / name
            retired.parent.mkdir(parents=True, exist_ok=True)
            path.rename(retired)
        # This deletion was requested by the group selection, not a local edit.
        # Retire only this path's remembered entry; preserve all other conflict state.
        run("chezmoi", "state", "delete", "--bucket=entryState", "--key=" + str(path))
    if plan.get("mise_handover") is not None:
        hand_over_mise(home, plan["mise_handover"], backup_path)
    import marketplaces

    if marketplaces.PENDING:
        marketplaces.save(home, marketplaces.PENDING, backup_path)
        marketplaces.PENDING.clear()
    # Agent outputs first: earlier skill links must leave before content installs skill folders.
    agent_deploy.apply(home, plan["agents"], wizard_catalog(), account)
    account.confirm_files(fingerprint)
    result = subprocess.run([bash(), str(ROOT / "scripts/apply.sh")])
    account.confirm_files(fingerprint)
    if result.returncode:
        raise RuntimeError(
            f"chezmoi apply failed with exit {result.returncode}; restore from {backup_path}"
        )
    account.confirm_files(fingerprint)
    run_index.stage("verify")
    status = run("chezmoi", "status")
    if status.strip():
        raise ValueError(kept_files_message(status))
    # Record the applied profile. A later saved-only change then triggers an update.
    record = json.loads((home / RECORD).read_text())
    record["profile_sha256"] = hashlib.sha256(
        (home / ".fleet/profile.toml").read_bytes()
    ).hexdigest()
    atomic(home / RECORD, json.dumps(record) + "\n")
    names = plan["names"] | set(plan["generated"])
    atomic(
        home / ".fleet/outputs.json",
        json.dumps({name: fingerprint(home / name) for name in sorted(names)}, indent=2) + "\n",
    )
    return account.finish("SUCCESS", warnings, "CLEAN (no differences)")


